def align_to_ink(atoms, i):
    """把 atoms 的包围盒线性映射到原图墨迹包围盒 (x/y 各自缩放)。"""
    bb = _ink_bbox(i)
    if not bb:
        return atoms
    ix0, iy0, ix1e, iy1e = bb
    ix1, iy1 = ix1e - 1, iy1e - 1
    gx = [a["x"] for a in atoms]
    gy = [a["y"] for a in atoms]
    gx0, gx1, gy0, gy1 = min(gx), max(gx), min(gy), max(gy)
    sx = (ix1 - ix0) / (gx1 - gx0) if gx1 > gx0 else 1.0
    sy = (iy1 - iy0) / (gy1 - gy0) if gy1 > gy0 else 1.0
    out = []
    for a in atoms:
        b = dict(a)
        b["x"] = round(ix0 + (a["x"] - gx0) * sx, 1)
        b["y"] = round(iy0 + (a["y"] - gy0) * sy, 1)
        out.append(b)
    return out

